"""Ports. Services depend on these; adapters implement them."""

from __future__ import annotations

from contextlib import AbstractContextManager
from typing import Protocol

from .domain import Decision, Document, EvalReport, ExtractionResult, GoldenExample, Label, Snapshot


class DecisionModel(Protocol):
    """Laya, or anything else returning a calibrated distribution over DOC_TYPES."""
    version: str
    def predict(self, text: str) -> dict[str, float]: ...


class FallbackClassifier(Protocol):
    actor: str
    def classify(self, text: str) -> str: ...


class Extractor(Protocol):
    doc_type: str
    def extract(self, doc: Document) -> ExtractionResult: ...


class TextStore(Protocol):
    def put(self, tenant_id: str, text: str) -> str: ...
    def get(self, uri: str) -> str: ...


class DecisionLog(Protocol):
    def append(self, decision: Decision) -> None: ...
    def get(self, decision_id: str) -> Decision: ...
    def all_for_tenant(self, tenant_id: str) -> list[Decision]: ...


class LabelRepository(Protocol):
    def add(self, label: Label) -> None: ...
    def for_decision(self, decision_id: str) -> list[Label]: ...


class GoldenSetRegistry(Protocol):
    """Frozen, read-only eval set. Training never sees these documents."""
    def version(self) -> str: ...
    def examples(self) -> tuple[GoldenExample, ...]: ...
    def doc_hashes(self) -> frozenset[str]: ...
    def template_groups(self) -> frozenset[str]: ...


class SnapshotStore(Protocol):
    def write(self, snapshot: Snapshot) -> str: ...
    def read(self, uri: str) -> Snapshot: ...


class Trainer(Protocol):
    """Returns a candidate model, or None when it only exported training data."""
    def fine_tune(self, base: DecisionModel, snapshot: Snapshot, texts: TextStore,
                  new_version: str) -> DecisionModel | None: ...


class ModelRegistry(Protocol):
    def current(self) -> DecisionModel: ...
    def register(self, model: DecisionModel, report: EvalReport, snapshot_uri: str) -> None: ...
    def promote(self, version: str) -> None: ...


class ReviewQueue(Protocol):
    def push(self, decision: Decision, reason: str) -> None: ...
    def drain(self) -> list[tuple[Decision, str]]: ...


class Span(Protocol):
    """One step in a trace. Attribute values are str, bool, int, float, or a dict of those."""
    def set(self, **attributes: object) -> None: ...
    def event(self, name: str, **attributes: object) -> None: ...


class Tracer(Protocol):
    """Nested, timed steps for one run. Spans opened inside another span become its children."""
    def span(self, name: str, **attributes: object) -> AbstractContextManager[Span]: ...
    def close(self) -> str | None: ...
